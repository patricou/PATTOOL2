package com.pat.controller.dto;

import java.util.ArrayList;
import java.util.Date;
import java.util.List;

/**
 * Open tasks for the home dashboard. Cover images, descriptions and completed items are omitted.
 */
public class TodoDashboardListDto {

    private String id;
    private String name;
    private String status;
    private String ownerMemberId;
    private String ownerName;
    private List<Item> items = new ArrayList<>();

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getOwnerMemberId() {
        return ownerMemberId;
    }

    public void setOwnerMemberId(String ownerMemberId) {
        this.ownerMemberId = ownerMemberId;
    }

    public String getOwnerName() {
        return ownerName;
    }

    public void setOwnerName(String ownerName) {
        this.ownerName = ownerName;
    }

    public List<Item> getItems() {
        return items;
    }

    public void setItems(List<Item> items) {
        this.items = items;
    }

    public static class Item {
        private String id;
        private String title;
        private String status;
        private Date dueDate;
        private String assigneeMemberId;
        private String assigneeName;

        public String getId() {
            return id;
        }

        public void setId(String id) {
            this.id = id;
        }

        public String getTitle() {
            return title;
        }

        public void setTitle(String title) {
            this.title = title;
        }

        public String getStatus() {
            return status;
        }

        public void setStatus(String status) {
            this.status = status;
        }

        public Date getDueDate() {
            return dueDate;
        }

        public void setDueDate(Date dueDate) {
            this.dueDate = dueDate;
        }

        public String getAssigneeMemberId() {
            return assigneeMemberId;
        }

        public void setAssigneeMemberId(String assigneeMemberId) {
            this.assigneeMemberId = assigneeMemberId;
        }

        public String getAssigneeName() {
            return assigneeName;
        }

        public void setAssigneeName(String assigneeName) {
            this.assigneeName = assigneeName;
        }
    }
}
